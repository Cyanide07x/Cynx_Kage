// ─────────────────────────────────────────────────────────────────────────────
// main.dart
// Entry point for the Cynx Kage shopping app.
//
// Flow:
//   1. Firebase is initialised.
//   2. [SplashScreen] plays a 3-second animation.
//   3. [checkLoginStatus] checks whether a Firebase user is already signed in.
//   4. The user is routed to [NavigationShell] (home) or [LoginScreen].
// ─────────────────────────────────────────────────────────────────────────────

import 'package:flutter/material.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:firebase_auth/firebase_auth.dart';

import 'firebase_options.dart';
import 'screens/splash/splash_screen.dart';
import 'screens/login/login_screen.dart';
import 'screens/navigation/navigation_shell.dart';

/// A global [NavigatorState] key used to push routes from outside the widget
/// tree (e.g. after the splash animation completes in [SplashScreen]).
final GlobalKey<NavigatorState> navKey = GlobalKey<NavigatorState>();

/// Returns `true` when a Firebase user session is still active,
/// meaning the user does not need to log in again.
Future<bool> checkLoginStatus() async {
  return FirebaseAuth.instance.currentUser != null;
}

Future<void> main() async {
  // Ensure Flutter engine bindings are ready before calling native APIs.
  WidgetsFlutterBinding.ensureInitialized();

  // Initialise Firebase using the platform-specific options generated by
  // the FlutterFire CLI (`firebase_options.dart`).
  await Firebase.initializeApp(
    options: DefaultFirebaseOptions.currentPlatform,
  );

  runApp(const CynxKageApp());
}

/// Root widget of the application.
///
/// Configures [MaterialApp] with a dark Material 3 theme and delegates
/// the initial routing decision to [SplashScreen.onFinished].
class CynxKageApp extends StatelessWidget {
  const CynxKageApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'Cynx Kage',
      navigatorKey: navKey,
      debugShowCheckedModeBanner: false,
      theme: ThemeData(
        brightness: Brightness.dark,
        useMaterial3: true,
      ),
      home: SplashScreen(
        // Called once the 3-second splash animation finishes.
        onFinished: () async {
          final isLoggedIn = await checkLoginStatus();

          if (isLoggedIn) {
            // Active session → go straight to the main shell.
            navKey.currentState!.pushReplacement(
              MaterialPageRoute(
                builder: (_) => const NavigationShell(),
              ),
            );
          } else {
            // No session → require the user to log in.
            navKey.currentState!.pushReplacement(
              MaterialPageRoute(
                builder: (_) => const LoginScreen(),
              ),
            );
          }
        },
      ),
    );
  }
}